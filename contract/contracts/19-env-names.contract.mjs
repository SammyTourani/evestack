/**
 * Every `EVESTACK_*` variable the code reads must be one a reader could find.
 *
 * ── The bug this is for ──────────────────────────────────────────────────────
 *
 * `packages/dashboard/lib/alerts.ts` read `EVESTACK_DAILY_BUDGET_USD`. That is
 * not a variable. The real one is `EVESTACK_BUDGET_DAILY_USD` — the same four
 * words in a different order — and the transposition appeared in exactly three
 * lines, all inside that one file, so nothing in the repository ever
 * contradicted it loudly enough to be noticed.
 *
 * The consequence was not a wrong number, which someone would have queried. It
 * was the "Spend today" monitor stuck at `unknown` on every install ever made,
 * reporting "no cap is configured" while `@evestack/budget` enforced its $10/day
 * default a process away. A check that cannot fire is worse than a missing one,
 * because the page counts it among the ones that passed.
 *
 * It was found by reading. This is the machine that would have found it: a name
 * nobody documents is either a typo or an undocumented feature, and both are
 * worth a failure.
 *
 * ── Why the allowlist is a list of names and not a switch ────────────────────
 *
 * Some variables really are internal — set by one process and read by another,
 * never by a human. Those are listed below BY NAME with a reason, so adding one
 * is a deliberate line in a diff rather than a flag someone flips once. A
 * regex-shaped exemption would have let the bug through: `EVESTACK_DAILY_*` is
 * exactly the shape a careless exemption would have covered.
 *
 * Scope is `repo`: it describes this checkout, not eve.
 */
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { REPO_ROOT } from "../lib/repo.mjs";

/** Where a human could reasonably learn a variable exists. */
const DOCUMENTATION = [
  "templates/default/.env.example",
  "packages/dashboard/.env.example",
  "README.md",
  "llms.txt",
];

/** Every .mdx under docs/, plus every package README. Read once. */
function documentationText() {
  let text = "";
  for (const file of DOCUMENTATION) {
    try {
      text += readFileSync(join(REPO_ROOT, file), "utf8");
    } catch {
      /* a missing optional doc is contract 16's problem, not this one */
    }
  }
  for (const entry of walk(join(REPO_ROOT, "docs"))) {
    if (entry.endsWith(".mdx") || entry.endsWith(".md")) text += readFileSync(entry, "utf8");
  }
  for (const pkg of readdirSync(join(REPO_ROOT, "packages"))) {
    for (const name of ["README.md", ".env.example"]) {
      try {
        text += readFileSync(join(REPO_ROOT, "packages", pkg, name), "utf8");
      } catch {
        /* not every package has both */
      }
    }
  }
  return text;
}

/**
 * Set by one process and read by another, or by a test. Each needs a reason,
 * because an entry here is a promise that a human never has to know about it.
 */
const INTERNAL = new Map([
  ["EVESTACK_PROBE_AGENT_URL", "set by .github/workflows/ci.yml for the runtime tier"],
  ["EVESTACK_PROBE_DASHBOARD_URL", "set by ci.yml for the seam probes"],
  ["EVESTACK_PROBE_DASHBOARD_USER", "set by ci.yml for the seam probes"],
  ["EVESTACK_PROBE_DASHBOARD_PASSWORD", "set by ci.yml for the seam probes"],
  ["EVESTACK_PROBE_INGEST_TOKEN", "set by ci.yml for the trace-ingest probe"],
  ["EVESTACK_PROBE_DISCORD_PRIVATE_KEY", "generated by ci.yml, thrown away with the job"],
  ["EVESTACK_AUTH_", "a prefix in a comment, not a variable"],
]);

/**
 * `.output` is Nitro's build directory and `.next` is Next's. Both inline the
 * template's source into bundles, so scanning them reports every variable a
 * second time and cites a generated chunk as the place to fix it.
 */
const SKIP_DIRS = new Set([
  "node_modules",
  ".git",
  ".next",
  ".output",
  "dist",
  ".eve",
  "coverage",
  ".turbo",
]);
const CODE = /\.(?:ts|tsx|mjs|js|cjs)$/;

function* walk(dir) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    let stats;
    try {
      stats = statSync(full);
    } catch {
      continue;
    }
    if (stats.isDirectory()) yield* walk(full);
    else yield full;
  }
}

/**
 * `process.env.EVESTACK_X` and `env.EVESTACK_X`, which is how lib/budget-env.ts
 * reads them (it takes the env as an argument so it can be tested), plus the
 * bracket form. A name only mentioned in prose is not a read and is ignored —
 * this is about what the code actually asks the environment for.
 */
const READS = [
  /process\.env\.(EVESTACK_[A-Z0-9_]+)/g,
  /(?<!process\.)\benv\.(EVESTACK_[A-Z0-9_]+)/g,
  /process\.env\[["'](EVESTACK_[A-Z0-9_]+)["']\]/g,
];

export default {
  id: "env/every-name-the-code-reads-is-findable",
  title: "every EVESTACK_* variable the code reads is documented or listed as internal",
  scope: "repo",
  assumption:
    "A variable name that appears nowhere a reader could find it is either a typo or an " +
    "undocumented feature. Both deserve a failure, and the typo is the one that has already " +
    "shipped: lib/alerts.ts read EVESTACK_DAILY_BUDGET_USD for the life of the file, which is " +
    "EVESTACK_BUDGET_DAILY_USD with two words swapped, so the spend monitor reported 'no cap is " +
    "configured' on every install while @evestack/budget enforced one.",
  evestackUse:
    "The Spend today monitor sat at `unknown` on every install in existence, counted among the " +
    "checks that passed. Found by a person reading two files side by side; findable by this in " +
    "a second.",

  async check(_eve, t) {
    const docs = documentationText();
    const found = new Map();

    for (const file of walk(REPO_ROOT)) {
      if (!CODE.test(file)) continue;
      const rel = relative(REPO_ROOT, file);
      // The contract tier reads its own source; skip it so the names quoted in
      // this file's own prose are not mistaken for reads.
      if (rel.startsWith("contract/contracts/19-")) continue;
      // packages/create-evestack/template is a COPY of templates/default,
      // written by scripts/sync-template.mjs before publish. Scanning both
      // reports every template variable twice and, worse, names the generated
      // copy as the place to go and fix it.
      if (rel.startsWith("packages/create-evestack/template/")) continue;
      const source = readFileSync(file, "utf8");
      for (const pattern of READS) {
        for (const match of source.matchAll(pattern)) {
          const name = match[1];
          if (!found.has(name)) found.set(name, rel);
        }
      }
    }

    // ANTI-VACUITY. A walk that silently stopped finding files — a renamed
    // directory, a broken regex — would report zero reads and pass every
    // assertion below by having nothing to check.
    t.ok(
      found.size >= 20,
      `the scan found ${found.size} EVESTACK_* reads across the workspace`,
      {
        expected: ">= 20 — the dashboard alone reads about thirty",
        actual: `${found.size}; a low count means the walk or the patterns stopped matching, and every check below would pass on an empty set`,
      },
    );

    for (const [name, where] of [...found].sort()) {
      if (INTERNAL.has(name)) continue;
      t.ok(
        docs.includes(name),
        `${name} (read in ${where}) appears somewhere a reader could find it`,
        {
          expected: "named in an .env.example, a README, or docs/",
          actual:
            "found nowhere — if this is a typo it is the alerts.ts bug again; if it is real, " +
            "document it or add it to INTERNAL with a reason",
        },
      );
    }

    // The allowlist has to stay honest too: an entry for a name nothing reads
    // any more is a stale exemption, and the next typo that matches it gets in
    // free.
    for (const [name, reason] of INTERNAL) {
      if (name.endsWith("_")) continue; // the documented prefix entry
      t.ok(
        found.has(name),
        `the internal allowlist entry ${name} is still read by something (${reason})`,
        {
          expected: "at least one read in the workspace",
          actual: "none — remove it, or it exempts a future typo that happens to match",
        },
      );
    }
  },
};
